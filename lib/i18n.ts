export function langFromPath(pathname: string | null | undefined): Lang {
  return pathname && pathname.startsWith('/en') ? 'en' : 'zh';
}

export function pathFor(lang: Lang, path = '/'): string {
  if (lang === 'en') return path === '/' ? '/en' : `/en${path}`;
  return path;
}
